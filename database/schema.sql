-- =====================================================================
-- Skema database Ignis (PostgreSQL) — mengikuti ERD proyek.
-- Dihasilkan dari Ignis.Api/Data/AppDbContext.cs
-- (db.Database.GenerateCreateScript()), lalu ditambah sequence Id di bagian paling bawah.
-- Bila model berubah, hasilkan ulang tabelnya dan pertahankan bagian sequence.
--
-- Pemetaan ERD -> tabel:
--   USER              -> users                (nama "user" kata cadangan di PostgreSQL)
--   ADMIN             -> admins               (PK sekaligus FK user_id)
--   REGISTERED_USER   -> registered_users     (PK sekaligus FK user_id)
--   MONITORING_AREA   -> monitoring_areas
--   HOTSPOT           -> hotspots
--   SATELLITE_HOTSPOT -> satellite_hotspots   (PK sekaligus FK hotspot_id)
--   MANUAL_HOTSPOT    -> manual_hotspots      (PK sekaligus FK hotspot_id)
--   NOTIFICATION      -> notifications
--   WEATHER_DATA      -> weather_data
--   PREDICTION        -> predictions
--
-- Tambahan di luar ERD (dibutuhkan fitur yang sudah ada di aplikasi):
--   users.token_version     nomor versi token; dinaikkan saat logout/ganti password/role/nonaktif sehingga token lama tidak berlaku
--   users.google_subject    id akun Google ("sub"), kunci login Google; null bila belum tertaut
--   users.is_active         status aktif/nonaktif pengguna (halaman Pengguna)
--   manual_hotspots.note    catatan laporan pada form hotspot manual
--   activity_log            log aktivitas (halaman Pengguna)
--   monitoring_areas.latitude/longitude   titik pusat lokasi tersimpan (rumah); min/max dihitung dari titik dan radius (km)
--   notifications.area_id/kind/level/eta_hours/distance_km   lokasi yang terancam, jenis (Fire/Smoke), tingkat 1-3,
--                           perkiraan jam tiba, dan jarak, hasil simulasi api dan asap
--   app_settings            pengaturan server yang diubah lewat aplikasi (override API key, terenkripsi)
--
-- Catatan: relasi "monitors / refers to" antara MONITORING_AREA dan HOTSPOT pada ERD tidak punya kolom FK;
-- diperlakukan sebagai relasi spasial (hotspot berada di dalam kotak lat/lon area) dan dihitung lewat MonitoringArea.Contains().
-- =====================================================================

CREATE TABLE activity_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    message text NOT NULL,
    created_at timestamp without time zone NOT NULL,
    CONSTRAINT "PK_activity_log" PRIMARY KEY (id)
);
CREATE TABLE hotspots (
    hotspot_id character varying(20) NOT NULL,
    source character varying(12) NOT NULL,
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    detected_at timestamp without time zone NOT NULL,
    confidence double precision NOT NULL,
    brightness double precision NOT NULL,
    status character varying(12) NOT NULL,
    CONSTRAINT "PK_hotspots" PRIMARY KEY (hotspot_id),
    CONSTRAINT ck_hotspots_confidence CHECK (confidence BETWEEN 0 AND 100),
    CONSTRAINT ck_hotspots_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_hotspots_lon CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_hotspots_source CHECK (source IN ('Satellite','Manual')),
    CONSTRAINT ck_hotspots_status CHECK (status IN ('Active','Monitoring','Resolved'))
);
CREATE TABLE users (
    user_id character varying(40) NOT NULL,
    name character varying(120) NOT NULL,
    email character varying(254) NOT NULL,
    password_hash text NOT NULL,
    role character varying(12) NOT NULL,
    created_at timestamp without time zone NOT NULL,
    is_active boolean NOT NULL,
    token_version integer NOT NULL DEFAULT 0,
    google_subject character varying(255),
    CONSTRAINT "PK_users" PRIMARY KEY (user_id),
    CONSTRAINT ck_users_role CHECK (role IN ('Admin','Registered'))
);
CREATE TABLE manual_hotspots (
    hotspot_id character varying(20) NOT NULL,
    reported_by character varying(120) NOT NULL,
    note character varying(1000) NOT NULL,
    incident_time timestamp without time zone NOT NULL,
    CONSTRAINT "PK_manual_hotspots" PRIMARY KEY (hotspot_id),
    CONSTRAINT "FK_manual_hotspots_hotspots_hotspot_id" FOREIGN KEY (hotspot_id) REFERENCES hotspots (hotspot_id) ON DELETE CASCADE
);
CREATE TABLE satellite_hotspots (
    hotspot_id character varying(20) NOT NULL,
    satellite_name character varying(60) NOT NULL,
    instrument character varying(60) NOT NULL,
    scan_time timestamp without time zone NOT NULL,
    CONSTRAINT "PK_satellite_hotspots" PRIMARY KEY (hotspot_id),
    CONSTRAINT "FK_satellite_hotspots_hotspots_hotspot_id" FOREIGN KEY (hotspot_id) REFERENCES hotspots (hotspot_id) ON DELETE CASCADE
);
CREATE TABLE weather_data (
    weather_id character varying(40) NOT NULL,
    hotspot_id character varying(20) NOT NULL,
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    timestamp timestamp without time zone NOT NULL,
    temperature double precision NOT NULL,
    humidity double precision NOT NULL,
    wind_speed double precision NOT NULL,
    wind_direction double precision NOT NULL,
    pressure double precision NOT NULL,
    precipitation double precision NOT NULL,
    weather_condition character varying(120) NOT NULL,
    CONSTRAINT "PK_weather_data" PRIMARY KEY (weather_id),
    CONSTRAINT "FK_weather_data_hotspots_hotspot_id" FOREIGN KEY (hotspot_id) REFERENCES hotspots (hotspot_id) ON DELETE CASCADE
);
CREATE TABLE admins (
    user_id character varying(40) NOT NULL,
    CONSTRAINT "PK_admins" PRIMARY KEY (user_id),
    CONSTRAINT "FK_admins_users_user_id" FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);
CREATE TABLE registered_users (
    user_id character varying(40) NOT NULL,
    CONSTRAINT "PK_registered_users" PRIMARY KEY (user_id),
    CONSTRAINT "FK_registered_users_users_user_id" FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);
CREATE TABLE predictions (
    prediction_id character varying(20) NOT NULL,
    hotspot_id character varying(20) NOT NULL,
    weather_id character varying(40),
    spread_direction double precision NOT NULL,
    spread_speed double precision NOT NULL,
    estimated_area double precision NOT NULL,
    estimated_time double precision NOT NULL,
    risk_level character varying(10) NOT NULL,
    created_at timestamp without time zone NOT NULL,
    CONSTRAINT "PK_predictions" PRIMARY KEY (prediction_id),
    CONSTRAINT ck_predictions_risk CHECK (risk_level IN ('Low','Medium','High','Critical')),
    CONSTRAINT "FK_predictions_hotspots_hotspot_id" FOREIGN KEY (hotspot_id) REFERENCES hotspots (hotspot_id) ON DELETE CASCADE,
    CONSTRAINT "FK_predictions_weather_data_weather_id" FOREIGN KEY (weather_id) REFERENCES weather_data (weather_id) ON DELETE SET NULL
);
CREATE TABLE monitoring_areas (
    area_id character varying(40) NOT NULL,
    user_id character varying(40) NOT NULL,
    name character varying(120) NOT NULL,
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    min_latitude double precision NOT NULL,
    max_latitude double precision NOT NULL,
    min_longitude double precision NOT NULL,
    max_longitude double precision NOT NULL,
    radius double precision NOT NULL,
    CONSTRAINT "PK_monitoring_areas" PRIMARY KEY (area_id),
    CONSTRAINT ck_monitoring_areas_lat CHECK (min_latitude <= max_latitude AND min_latitude >= -90 AND max_latitude <= 90),
    CONSTRAINT ck_monitoring_areas_lon CHECK (min_longitude <= max_longitude AND min_longitude >= -180 AND max_longitude <= 180),
    CONSTRAINT ck_monitoring_areas_radius CHECK (radius >= 0),
    CONSTRAINT "FK_monitoring_areas_registered_users_user_id" FOREIGN KEY (user_id) REFERENCES registered_users (user_id) ON DELETE CASCADE
);
CREATE TABLE notifications (
    notification_id character varying(40) NOT NULL,
    user_id character varying(40) NOT NULL,
    hotspot_id character varying(20) NOT NULL,
    area_id character varying(40),
    kind character varying(10) NOT NULL,
    level integer NOT NULL,
    eta_hours integer NOT NULL,
    distance_km double precision NOT NULL,
    title character varying(200) NOT NULL,
    message text NOT NULL,
    created_at timestamp without time zone NOT NULL,
    is_read boolean NOT NULL,
    CONSTRAINT "PK_notifications" PRIMARY KEY (notification_id),
    CONSTRAINT "FK_notifications_hotspots_hotspot_id" FOREIGN KEY (hotspot_id) REFERENCES hotspots (hotspot_id) ON DELETE CASCADE,
    CONSTRAINT "FK_notifications_monitoring_areas_area_id" FOREIGN KEY (area_id) REFERENCES monitoring_areas (area_id) ON DELETE CASCADE,
    CONSTRAINT "FK_notifications_registered_users_user_id" FOREIGN KEY (user_id) REFERENCES registered_users (user_id) ON DELETE CASCADE
);
CREATE INDEX "IX_activity_log_created_at" ON activity_log (created_at);
CREATE INDEX "IX_hotspots_detected_at" ON hotspots (detected_at);
CREATE UNIQUE INDEX "IX_hotspots_detected_at_latitude_longitude" ON hotspots (detected_at, latitude, longitude) WHERE source = 'Satellite';
CREATE INDEX "IX_monitoring_areas_user_id" ON monitoring_areas (user_id);
CREATE INDEX "IX_notifications_area_id" ON notifications (area_id);
CREATE INDEX "IX_notifications_hotspot_id" ON notifications (hotspot_id);
CREATE INDEX "IX_notifications_user_id_created_at" ON notifications (user_id, created_at);
CREATE INDEX "IX_notifications_user_id_is_read" ON notifications (user_id, is_read);
CREATE INDEX "IX_predictions_hotspot_id_created_at" ON predictions (hotspot_id, created_at);
CREATE INDEX "IX_predictions_weather_id" ON predictions (weather_id);
CREATE UNIQUE INDEX "IX_users_email" ON users (email);
CREATE UNIQUE INDEX "IX_users_google_subject" ON users (google_subject) WHERE google_subject IS NOT NULL;
CREATE INDEX "IX_weather_data_hotspot_id_timestamp" ON weather_data (hotspot_id, timestamp);

-- ---------------------------------------------------------------------
-- Sequence untuk Id berformat "PREFIX-0001" (HS-, WX-, PR-, U-, AR-, NT-).
-- Id dibuat server dengan nextval() sehingga dua penulis bersamaan tidak pernah mendapat nomor yang sama.
-- Mulai dari 1000: nomor di bawahnya dipakai data demo. Ignis.Api juga membuatnya (IF NOT EXISTS) saat start.
-- ---------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS ignis_hotspot_seq START 1000;
CREATE SEQUENCE IF NOT EXISTS ignis_weather_seq START 1000;
CREATE SEQUENCE IF NOT EXISTS ignis_prediction_seq START 1000;
CREATE SEQUENCE IF NOT EXISTS ignis_user_seq START 1000;
CREATE SEQUENCE IF NOT EXISTS ignis_area_seq START 1000;           -- lokasi tersimpan (AR-1000, ...)
CREATE SEQUENCE IF NOT EXISTS ignis_notification_seq START 1000;   -- notifikasi (NT-1000, ...)

-- ---------------------------------------------------------------------
-- Pengaturan server yang diubah lewat aplikasi (saat ini: override API key FIRMS/OpenWeather).
-- Kolom value SELALU terenkripsi (ASP.NET Data Protection), tidak pernah teks biasa.
-- Ignis.Api juga membuatnya (IF NOT EXISTS) saat start, termasuk di database lama yang dibuat sebelum tabel ini ada.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app_settings (
    setting_key character varying(100) NOT NULL PRIMARY KEY,
    value text NOT NULL,
    updated_at timestamp without time zone NOT NULL,
    updated_by character varying(254) NULL
);
